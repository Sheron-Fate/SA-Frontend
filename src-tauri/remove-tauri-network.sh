#!/bin/bash

# Скрипт для удаления виртуального сетевого интерфейса

echo "Удаление виртуального интерфейса 172.20.10.3..."

sudo ifconfig lo0 -alias 172.20.10.3

if ifconfig lo0 | grep -q "172.20.10.3"; then
    echo "❌ Ошибка удаления интерфейса"
    exit 1
else
    echo "✅ Виртуальный интерфейс 172.20.10.3 удален"
fi

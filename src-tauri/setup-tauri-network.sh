#!/bin/bash

# Скрипт для настройки виртуальной LAN для Tauri

echo "Настройка виртуального сетевого интерфейса для Tauri..."

# Проверить, существует ли уже интерфейс
if ifconfig lo0 | grep -q "172.20.10.3"; then
    echo "✅ Виртуальный интерфейс 172.20.10.3 уже существует"
else
    echo "Создание виртуального интерфейса 172.20.10.3..."
    sudo ifconfig lo0 alias 172.20.10.3 netmask 255.255.255.0
    
    if ifconfig lo0 | grep -q "172.20.10.3"; then
        echo "✅ Виртуальный интерфейс 172.20.10.3 успешно создан"
    else
        echo "❌ Ошибка создания виртуального интерфейса"
        exit 1
    fi
fi

# Проверить доступность бэкенда
echo ""
echo "Проверка доступности бэкенда..."
if curl -s http://172.20.10.3:8080/api/pigments > /dev/null 2>&1; then
    echo "✅ Бэкенд доступен на http://172.20.10.3:8080"
else
    echo "⚠️  Бэкенд недоступен на http://172.20.10.3:8080"
    echo "Убедитесь, что Go сервер запущен и слушает на всех интерфейсах (0.0.0.0:8080)"
fi

echo ""
echo "Готово! Теперь можно запускать Tauri приложение."
